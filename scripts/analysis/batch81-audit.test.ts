declare const process: { env: Record<string, string | undefined> };
const runs = allAuditRuns();
const f0 = (x: number, d = 0) => x.toFixed(d);

const pearson = (a: number[], b: number[]) => {
  const n = a.length, ma = a.reduce((s, x) => s + x, 0) / n, mb = b.reduce((s, x) => s + x, 0) / n;
  let c = 0, va = 0, vb = 0;
  for (let i = 0; i < n; i++) { c += (a[i] - ma) * (b[i] - mb); va += (a[i] - ma) ** 2; vb += (b[i] - mb) ** 2; }
  return va && vb ? c / Math.sqrt(va * vb) : 0;
};
const rank = (xs: number[]) => { const o = xs.map((x, i) => ({ x, i })).sort((p, q) => q.x - p.x); const r = Array(xs.length); o.forEach((e, k) => (r[e.i] = k + 1)); return r as number[]; };
const spearman = (a: number[], b: number[]) => pearson(rank(a), rank(b));

interface Row { run: AuditRun; q: number; price: number; terminal: number; functional: Record<V2Role, number>; company: number; aiShare: number }
function rowAt(run: AuditRun, q: number): Row {
  const recs = run.records.slice(0, q);
  const cards = allScorecards(recs, q);
  const inv = recs.reduce((t, h) => t + h.consequence.ledger.strategicInvestment, 0);
  const ai = recs.reduce((t, h) => t + h.consequence.ledger.strategicInvestmentByBucket.aiProduct, 0);
  return {
    run, q, price: valuationSeries(recs).points[q].price, terminal: scoreV2Company(recs[q - 1].after).overall,
    functional: Object.fromEntries(cards.map(c => [c.role, c.functional])) as Record<V2Role, number>, company: cards[0].company, aiShare: inv > 0 ? ai / inv : 0,
  };
}
const exec = (r: Row, role: V2Role, w: number) => w * r.functional[role] + (1 - w) * r.company;
const rows8 = runs.map(r => rowAt(r, 8));

/** Deterministic pseudo-random classroom draws. */
function classrooms(n: number, size: number, seed = 7): AuditRun[][] {
  let s = seed;
  const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
  const pool = runs.filter(r => !r.tags.includes('insolvency'));
  const out: AuditRun[][] = [];
  for (let i = 0; i < n; i++) {
    const picked = new Set<number>();
    while (picked.size < size) picked.add(Math.floor(rnd() * pool.length));
    out.push([...picked].map(k => pool[k]));
  }
  return out;
}

describe('Batch 8.1 audit', () => {
  it('covers every required strategy scenario', () => {
    expect(runs.length).toBeGreaterThanOrEqual(25);
    for (const fam of ['Hold most capital as cash', 'Concentrate on Consumer', 'Concentrate on Enterprise', 'Concentrate on AI/Product', 'Concentrate on People', 'Concentrate on University/Credentials', 'Diversified allocation', 'Aggressive growth with financing', 'Conservative financial management', 'Early investment, then strategic pivot', 'Delayed investment, aggressive catch-up', 'Strong early growth into the recession', 'Weak early performance, then recovery', 'High investment with execution overload', 'Becomes insolvent']) {
      expect(runs.some(r => r.family === fam), fam).toBe(true);
    }
    expect(runs.find(r => r.id === 'insolvency')!.records[7].after.solvency.everInsolvent).toBe(true);
  });
  it('a strategy with AI at most a quarter of investment reaches the top tier of share price and terminal score', () => {
    const top = [...rows8].sort((a, b) => b.price - a.price).slice(0, 8);
    expect(top.some(r => r.aiShare <= 0.25)).toBe(true);
  });

  it('writes the audit data when AUDIT_WRITE=1', () => {
    if (process.env.AUDIT_WRITE !== '1') return;
    const L: string[] = [];
    const s0 = startingCompany();
    L.push('# Batch 8.1 — audit data', '', 'Generated by `AUDIT_WRITE=1 npx vitest run scripts/analysis/batch81-audit.test.ts`. Every run is a valid policy through the frozen engine, replayed through the production path.', '');

    L.push('## 1. Strategy outcomes at Q4 2024', '', '| Strategy | Scenario | Destination | AI share of investment | Revenue | Op. profit | Cash | Liquidity | Share price | Terminal | CEO | CFO | CPO | CGO | CPeO |', '|---|---|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|');
    for (const r of rows8) {
      const s = r.run.records[7].after;
      const cards = SCORECARD_ROLES.map(role => `${f0(r.functional[role])} / ${f0(exec(r, role, 0.6))}`);
      L.push(`| ${r.run.name} | ${r.run.family} | ${s.destination?.id ?? '—'} | ${f0(r.aiShare * 100)}% | $${f0(s.revenue)}M | $${f0(s.operatingProfit)}M | $${f0(s.cash)}M | ${s.solvency.status}${s.solvency.distressed ? ', distressed' : ''}${s.solvency.everInsolvent ? ', was insolvent' : ''} | $${f0(r.price)} | ${f0(r.terminal)} | ${cards.join(' | ')} |`);
    }
    L.push('', 'Executive cells: functional / executive (60/40).', '');

    L.push('## 2. Trajectories (revenue, operating profit, cash, share price by quarter)', '');
    for (const run of runs) {
      const v = valuationSeries(run.records).points.map(p => f0(p.price));
      L.push(`**${run.name}** — revenue ${[s0.revenue, ...run.records.map(h => h.after.revenue)].map(x => f0(x)).join(' → ')}; op. profit ${[s0.operatingProfit, ...run.records.map(h => h.after.operatingProfit)].map(x => f0(x)).join(' → ')}; cash ${[s0.cash, ...run.records.map(h => h.after.cash)].map(x => f0(x)).join(' → ')}; price ${v.join(' → ')}`, '');
    }

    L.push('## 3. Score independence (Q8, all strategies)', '');
    const fun = (role: V2Role) => rows8.map(r => r.functional[role]);
    const price = rows8.map(r => r.price), term = rows8.map(r => r.terminal);
    L.push('| Functional score | Pearson vs share price | Spearman vs share price | Pearson vs terminal score |', '|---|---:|---:|---:|');
    for (const role of SCORECARD_ROLES) L.push(`| ${role} | ${f0(pearson(fun(role), price), 2)} | ${f0(spearman(fun(role), price), 2)} | ${f0(pearson(fun(role), term), 2)} |`);
    L.push('', '| Pearson between functional scores | ' + SCORECARD_ROLES.join(' | ') + ' |', '|---|' + '---:|'.repeat(5));
    for (const a of SCORECARD_ROLES) L.push(`| ${a} | ${SCORECARD_ROLES.map(b => f0(pearson(fun(a), fun(b)), 2)).join(' | ')} |`);

    L.push('', '## 4. Metric overlap (Pearson between metric scores across all strategy-quarters Q2–Q8)', '');
    const obs: Record<string, number[]> = {};
    for (const run of runs) for (let q = 2; q <= 8; q++) {
      const recs = run.records.slice(0, q);
      const ctx = { states: [s0, ...recs.map(h => h.after)], records: recs, t: q };
      for (const m of EXECUTIVE_METRICS) (obs[m.id] ??= []).push(metricScore(m, ctx) ?? 50);
    }
    const ids = EXECUTIVE_METRICS.map(m => m.id);
    const pairs: { a: string; b: string; r: number }[] = [];
    for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) pairs.push({ a: ids[i], b: ids[j], r: pearson(obs[ids[i]], obs[ids[j]]) });
    L.push('| Metric A | Metric B | Pearson |', '|---|---|---:|');
    for (const p of pairs.filter(p => Math.abs(p.r) >= 0.7).sort((x, y) => Math.abs(y.r) - Math.abs(x.r))) L.push(`| ${p.a} | ${p.b} | ${f0(p.r, 2)} |`);

    L.push('', '## 5. CFO: prudence vs inactivity (Q8)', '', '| Strategy | Cash | Revenue | CFO functional | rank (of ' + rows8.length + ') | Share-price rank | Hygiene points (liquidity, debt, ownership, warnings) |', '|---|---:|---:|---:|---:|---:|---:|');
    const cfoRank = rank(fun('CFO')), priceRank = rank(price);
    const hygieneIds = ['cfo-liquidity', 'cfo-debt', 'cfo-ownership', 'cfo-distress'];
    rows8.forEach((r, i) => {
      const recs = r.run.records;
      const ctx = { states: [s0, ...recs.map(h => h.after)], records: recs, t: 8 };
      const hyg = EXECUTIVE_METRICS.filter(m => hygieneIds.includes(m.id)).reduce((t, m) => t + m.weight * (metricScore(m, ctx) ?? 0), 0);
      L.push(`| ${r.run.name} | $${f0(recs[7].after.cash)}M | $${f0(recs[7].after.revenue)}M | ${f0(r.functional.CFO)} | ${cfoRank[i]} | ${priceRank[i]} | ${f0(hyg)} |`);
    });

    L.push('', '## 6. Weight sensitivity (functional / company)', '');
    const weights = [1, 0.7, 0.65, 0.6, 0.5];
    L.push('| Weights | Mean Pearson between executive scores of different roles | Spearman(CEO exec, CPeO exec) | Spearman(each role exec vs share price), mean | Max executive score of a team with share price < $100 |', '|---|---:|---:|---:|---:|');
    for (const w of weights) {
      const ex = (role: V2Role) => rows8.map(r => exec(r, role, w));
      let sum = 0, n = 0;
      for (let i = 0; i < 5; i++) for (let j = i + 1; j < 5; j++) { sum += pearson(ex(SCORECARD_ROLES[i]), ex(SCORECARD_ROLES[j])); n++; }
      const mp = SCORECARD_ROLES.reduce((t, role) => t + spearman(ex(role), price), 0) / 5;
      const weak = rows8.filter(r => r.price < 100);
      const maxWeak = Math.max(...weak.flatMap(r => SCORECARD_ROLES.map(role => exec(r, role, w))));
      L.push(`| ${w * 100}/${f0((1 - w) * 100)} | ${f0(sum / n, 2)} | ${f0(spearman(ex('CEO'), ex('People')), 2)} | ${f0(mp, 2)} | ${f0(maxWeak)} |`);
    }

    L.push('', '## 7. Award distribution — 300 simulated five-team classrooms (insolvent strategy excluded from the pool; awards at Q4, Q6, Q8)', '');
    L.push('| Award basis | Quarter | Classrooms where one team wins ≥ 5 of 6 awards | Mean distinct winning teams | Classrooms where the top share price wins every functional award | Shared awards |', '|---|---|---:|---:|---:|---:|');
    const rooms = classrooms(300, 5);
    const configs = [
      { label: 'Batch 8.1 engine: role awards on functional, team award on 60/40', roleW: 1, teamW: 0.6 },
      ...weights.map(w => ({ label: `Role and team awards on executive ${w * 100}/${f0((1 - w) * 100)}`, roleW: w, teamW: w })),
    ];
    for (const cfg of configs) for (const q of [4, 6, 8]) {
      const w = cfg.roleW;
      let sweep = 0, distinct = 0, priceSweep = 0, shared = 0;
      for (const room of rooms) {
        const rs = room.map(run => rowAt(run, q));
        const winners: string[] = [];
        for (const role of SCORECARD_ROLES) {
          const sc = rs.map(r => exec(r, role, w)); const top = Math.max(...sc);
          const ws = rs.filter((_, i) => top - sc[i] < 1).map(r => r.run.id); if (ws.length > 1) shared++;
          winners.push(...ws.slice(0, 1));
        }
        const team = rs.map(r => SCORECARD_ROLES.reduce((t, role) => t + exec(r, role, cfg.teamW), 0) / 5);
        winners.push(rs[team.indexOf(Math.max(...team))].run.id);
        const counts: Record<string, number> = {}; for (const x of winners) counts[x] = (counts[x] ?? 0) + 1;
        if (Math.max(...Object.values(counts)) >= 5) sweep++;
        distinct += Object.keys(counts).length;
        const bestPrice = rs[rs.map(r => r.price).indexOf(Math.max(...rs.map(r => r.price)))].run.id;
        if (winners.slice(0, 5).every(x => x === bestPrice)) priceSweep++;
      }
      L.push(`| ${cfg.label} | Q${q} | ${f0((sweep / rooms.length) * 100)}% | ${f0(distinct / rooms.length, 2)} | ${f0((priceSweep / rooms.length) * 100)}% | ${shared} |`);
    }

    L.push('', '## 8. Facilitator award engine on sample classrooms (current model)', '');
    for (const ids of [['consumer-ai', 'balanced', 'non-ai-consumer', 'people100', 'conservative'], ['evidence-responsive', 'value-over-org', 'non-ai-diversified', 'enterprise100', 'cash100'], ['premium-builder', 'pivot', 'insolvency', 'non-ai-university', 'delayed-catchup']]) {
      for (const q of [4, 6, 8]) {
        const res = computeAwards(ids.map(id => { const r = runs.find(x => x.id === id)!; return { teamId: id, teamName: id, records: r.records.slice(0, q) }; }));
        L.push(`- ${ids.join(', ')} @ Q${q}: ${res.available ? res.awards.map(a => `${a.id}→${a.winners.join('+')} (${f0(a.score, 1)})`).join('; ') : res.reason}${res.excluded.length ? ` · excluded: ${res.excluded.map(e => e.teamName).join(', ')}` : ''}`);
      }
    }
    L.push('', '## 9. Share price: feedback speed and dispersion by quarter', '', '| Quarter | Mean absolute quarterly move | Spread of prices across strategies (min – max) | Std. dev. of price |', '|---|---:|---:|---:|');
    for (let q = 1; q <= 8; q++) {
      const pts = runs.map(r => valuationSeries(r.records).points);
      const moves = pts.map(p => Math.abs(p[q].changePct));
      const prices = pts.map(p => p[q].price);
      const mean = prices.reduce((a, b) => a + b, 0) / prices.length;
      const sd = Math.sqrt(prices.reduce((a, b) => a + (b - mean) ** 2, 0) / prices.length);
      L.push(`| Q${q} | ${f0((moves.reduce((a, b) => a + b, 0) / moves.length) * 100, 1)}% | $${f0(Math.min(...prices))} – $${f0(Math.max(...prices))} | $${f0(sd, 1)} |`);
    }
    L.push('', `Share price vs terminal score at Q8: Pearson ${f0(pearson(price, term), 2)}, Spearman ${f0(spearman(price, term), 2)} (related lenses, not duplicates).`);
    L.push('', '## 10. Strategic diversity by destination (Q8)', '', '| Destination | Strategies | Best share price | Best terminal | Range of share price | Mean AI share of investment |', '|---|---:|---:|---:|---:|---:|');
    const byDest: Record<string, Row[]> = {};
    for (const r of rows8) (byDest[r.run.records[7].after.destination?.id ?? 'none'] ??= []).push(r);
    for (const [d, rs] of Object.entries(byDest)) L.push(`| ${d} | ${rs.length} | $${f0(Math.max(...rs.map(r => r.price)))} | ${f0(Math.max(...rs.map(r => r.terminal)))} | $${f0(Math.min(...rs.map(r => r.price)))} – $${f0(Math.max(...rs.map(r => r.price)))} | ${f0(rs.reduce((a, r) => a + r.aiShare, 0) / rs.length * 100)}% |`);
    L.push('', '## 11. AI share of investment vs outcome (Q8)', '', '| AI share of investment | Strategies | Best share price | Best terminal | Median share price |', '|---|---:|---:|---:|---:|');
    for (const [lo, hi, lab] of [[0, 0.05, '0–5% (no AI)'], [0.05, 0.3, '5–30% (AI as one of several)'], [0.3, 0.6, '30–60%'], [0.6, 1.01, '60%+ (AI-dominant)']] as const) {
      const rs = rows8.filter(r => r.aiShare >= lo && r.aiShare < hi);
      if (!rs.length) continue;
      const ps = rs.map(r => r.price).sort((a, b) => a - b);
      L.push(`| ${lab} | ${rs.length} | $${f0(ps[ps.length - 1])} | ${f0(Math.max(...rs.map(r => r.terminal)))} | $${f0(ps[Math.floor(ps.length / 2)])} |`);
    }
    L.push('', `Company component check: $50 → ${companyComponent(50)}, $100 → ${companyComponent(100)}, $165 → ${f0(companyComponent(165), 1)}.`);
    writeFileSync('docs/BATCH8_1_AUDIT_DATA.md', L.join('\n') + '\n');
  });
});
