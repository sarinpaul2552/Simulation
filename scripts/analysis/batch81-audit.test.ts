import { describe, it, expect } from 'vitest';
import { writeFileSync } from 'node:fs';
import { allAuditRuns, AuditRun } from '../../src/production/v2/testing/auditStrategies';
import { valuationSeries } from '../../src/production/v2/insights/valuation';
import { allScorecards, EXECUTIVE_METRICS, metricScore, SCORECARD_ROLES, computeAwards, companyComponent } from '../../src/production/v2/insights/executive';
import { startingCompany } from '../../src/production/v2/insights/history';
