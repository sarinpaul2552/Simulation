/**
 * Batch 8 · Stage 3 — calibration of the simulated share price and executive scorecards (ANALYSIS ONLY).
 * Runs every Test Lab arc strategy that starts from the real starting company, plus four financing-refusing variants
 * that drive the company into liquidity trouble, through the production replay path. With VAL_WRITE=1 it writes
 * docs/BATCH8_CALIBRATION_DATA.md; otherwise it only asserts the calibration properties.
 */
import { describe, it, expect } from 'vitest';
import { writeFileSync } from 'node:fs';
import { ARC_STRATEGIES, runArc, a, liquidityPolicy, V2ArcStrategy } from '../../src/testlab/utils/v2ScenarioArc';
import { inputsOf } from '../../src/production/v2/testing/arcGames';
import { replayInputs } from '../../src/production/v2/adapter';
import { gameHistory } from '../../src/production/v2/insights/history';
import { valuationSeries, VALUATION_CONFIG, FACTOR_IDS, FACTOR_INFO } from '../../src/production/v2/insights/valuation';
import { allScorecards } from '../../src/production/v2/insights/executive';
import { scoreV2Company } from '../../src/simulation/engineV2Scoring';

declare const process: { env: Record<string, string | undefined> };
const c = (x: ReturnType<typeof a>) => () => x;
const REFUSING: V2ArcStrategy[] = [
  { id: 'people-refuse', name: '$30M People, refuses financing', description: '', allocate: c(a({ people: 30 })), destination: () => 'premium-human-ai', policy: { liquidity: liquidityPolicy('refuse') } },
  { id: 'enterprise-refuse', name: '$30M Enterprise, refuses financing', description: '', allocate: c(a({ enterprise: 30 })), destination: () => 'enterprise-ai', policy: { liquidity: liquidityPolicy('refuse') } },
  { id: 'ai-refuse', name: '$30M AI, refuses financing', description: '', allocate: c(a({ aiProduct: 30 })), destination: () => 'enterprise-ai', policy: { liquidity: liquidityPolicy('refuse') } },
  { id: 'university-refuse', name: '$30M University, refuses financing', description: '', allocate: c(a({ universityCredentials: 30 })), destination: () => 'university-infrastructure', policy: { liquidity: liquidityPolicy('refuse') } },
];
const FAMILY: Record<string, string> = {
  cash100: 'Cash preservation', conservative: 'Cash preservation', consumer100: 'Concentrated', enterprise100: 'Concentrated', ai100: 'Concentrated',
  people100: 'Concentrated', university100: 'Concentrated', balanced: 'Diversified', 'consumer-ai': 'Paired', 'enterprise-ai': 'Paired',
  'evidence-responsive': 'Adaptive', 'wrong-way': 'Adaptive (contrarian)', 'premium-builder': 'Capability-led', 'credential-builder': 'Capability-led',
  aggressive: 'Aggressive growth', 'people-refuse': 'Distress test', 'enterprise-refuse': 'Distress test', 'ai-refuse': 'Distress test', 'university-refuse': 'Distress test',
};
const strategies = [...ARC_STRATEGIES.filter(s => !s.opening), ...REFUSING];
const runs = strategies.map(st => {
  const h = gameHistory(replayInputs(inputsOf(runArc(st, 8))));
  const v = valuationSeries(h);
  const cards = allScorecards(h);
  return { st, h, v, cards, s: h[7].after, score: scoreV2Company(h[7].after) };
});

describe('Batch 8 valuation calibration', () => {
  it('covers at least eight strategies across families', () => {
    expect(runs.length).toBeGreaterThanOrEqual(8);
    expect(new Set(runs.map(r => FAMILY[r.st.id])).size).toBeGreaterThanOrEqual(6);
  });
  it('produces a meaningful spread without runaway prices', () => {
    const p8 = runs.map(r => r.v.points[8].price);
    expect(Math.max(...p8) - Math.min(...p8)).toBeGreaterThan(50);
    expect(Math.max(...p8)).toBeLessThan(250);
    expect(Math.min(...p8)).toBeGreaterThan(20);
  });
  it('the share price rank broadly agrees with the frozen terminal score (Spearman ≥ 0.6)', () => {
    const rank = (xs: number[]) => { const o = xs.map((x, i) => ({ x, i })).sort((p, q) => p.x - q.x); const r = Array(xs.length); o.forEach((e, k) => (r[e.i] = k)); return r; };
    const a1 = rank(runs.map(r => r.v.points[8].price)), a2 = rank(runs.map(r => r.score.overall));
    const n = a1.length; const d2 = a1.reduce((t, x, i) => t + (x - a2[i]) ** 2, 0);
    expect(1 - (6 * d2) / (n * (n * n - 1))).toBeGreaterThanOrEqual(0.6);
  });
  it('writes the calibration data when VAL_WRITE=1', () => {
    if (process.env.VAL_WRITE !== '1') return;
    const f = (x: number, d = 0) => x.toFixed(d);
    const lines: string[] = [];
    lines.push('# Batch 8 — Valuation and executive scorecard calibration data', '');
    lines.push(`Generated by \`VAL_WRITE=1 npx vitest run scripts/analysis/valuation-calibration.test.ts\`. Model ${VALUATION_CONFIG.version}; weights ${FACTOR_IDS.map(k => `${FACTOR_INFO[k].label} ${VALUATION_CONFIG.weights[k] * 100}%`).join(', ')}; multiplier ${VALUATION_CONFIG.multiplier}; quarterly limit ±${VALUATION_CONFIG.quarterlyCap * 100}%.`, '');
    lines.push('## Share price path (Q4 2022 → Q4 2024)', '', '| Strategy | Family | Q0 | Q1 | Q2 | Q3 | Q4 | Q5 | Q6 | Q7 | Q8 | Revenue Q8 | Cash Q8 | Liquidity | Terminal score |', '|---|---|' + '---:|'.repeat(13));
    for (const r of runs) lines.push(`| ${r.st.name} | ${FAMILY[r.st.id]} | ${r.v.points.map(p => f(p.price)).join(' | ')} | $${f(r.s.revenue)}M | $${f(r.s.cash)}M | ${r.s.solvency.status}${r.s.solvency.distressed ? ', distressed' : ''}${r.s.solvency.everInsolvent ? ', was insolvent' : ''} | ${f(r.score.overall)} |`);
    lines.push('', '## Q8 factor scores (0–1) and present vs expectations', '', '| Strategy | Growth | Profitability | Readiness | Retention | Financial | Distress | Ownership | Present $ | Expectations $ |', '|---|' + '---:|'.repeat(9));
    for (const r of runs) { const p = r.v.points[8]; lines.push(`| ${r.st.name} | ${FACTOR_IDS.map(k => p.factors[k].toFixed(2)).join(' | ')} | ${f(p.distress * 100)}% | ${f(p.ownership * 100)}% | ${p.presentContribution >= 0 ? '+' : ''}${f(p.presentContribution, 1)} | ${p.expectationsContribution >= 0 ? '+' : ''}${f(p.expectationsContribution, 1)} |`); }
    lines.push('', '## Executive scores at Q8 (functional / executive)', '', '| Strategy | CEO | CFO | Product | Growth | People | Company component |', '|---|' + '---:|'.repeat(6));
    for (const r of runs) lines.push(`| ${r.st.name} | ${r.cards.map(x => `${f(x.functional)} / ${f(x.executive)}`).join(' | ')} | ${f(r.cards[0].company)} |`);
    lines.push('', '## Largest single-quarter moves', '', '| Strategy | Quarter | Change | Main drivers |', '|---|---:|---:|---|');
    for (const r of runs) { const p = [...r.v.points.slice(1)].sort((x, y) => Math.abs(y.changePct) - Math.abs(x.changePct))[0]; lines.push(`| ${r.st.name} | Q${p.quarter} | ${(p.changePct * 100).toFixed(1)}% | ${[...p.bridge].sort((x, y) => Math.abs(y.amount) - Math.abs(x.amount)).slice(0, 2).map(b => `${b.label} ${b.amount >= 0 ? '+' : '−'}$${Math.abs(b.amount).toFixed(2)}`).join('; ')} |`); }
    writeFileSync('docs/BATCH8_CALIBRATION_DATA.md', lines.join('\n') + '\n');
  });
});
